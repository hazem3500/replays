import checkout from './data/demo-seed-checkout-error.json' with { type: 'json' };
import diagnostics from './data/demo-seed-console-diagnostics.json' with { type: 'json' };
import search from './data/demo-seed-dashboard-search.json' with { type: 'json' };
import activity from './data/demo-seed-long-activity.json' with { type: 'json' };
import retry from './data/demo-seed-network-retry.json' with { type: 'json' };
import signup from './data/demo-seed-signup.json' with { type: 'json' };
import { assertReplayBundle, summarizeReplay, type ReplayBundle } from '../../src/shared/replay.ts';
import type { FeedEntry } from '../../src/client/index/Feed.tsx';
import type { ReviewSuiteIndexEntry } from '../../src/shared/review-suite.ts';

// Snapshots generated by scripts/demo-seed.mjs, checked in here so stories do not need an API or seed run.
function validated(value: unknown): ReplayBundle {
  assertReplayBundle(value);
  return value;
}
export const samples = [checkout, diagnostics, search, activity, retry, signup].map(validated);
export function replay(overrides: Partial<ReplayBundle> = {}): ReplayBundle {
  return { ...structuredClone(samples[0]!), ...overrides };
}
export function emptyReplay(): ReplayBundle {
  const bundle = replay({
    console: [],
    network: [],
    steps: [],
    performance: { supported: [], entries: [] },
  });
  delete bundle.context;
  return bundle;
}
export function denseReplay(): ReplayBundle {
  const base = replay();
  return replay({
    console: Array.from({ length: 120 }, (_, i) => ({
      at: i * 60,
      level: i % 5 === 0 ? 'error' : 'log',
      message: `Request ${i}: ${'a long diagnostic message with request context · '.repeat((i % 6) + 1)}`,
    })),
    network: Array.from({ length: 80 }, (_, i) => ({
      ...base.network[i % base.network.length]!,
      id: `dense-${i}`,
      at: i * 80,
      url: `https://api.northstar.demo.test/v1/checkout/${i}?query=${'long-value-'.repeat(8)}`,
    })),
  });
}
export const summaries = samples.map(summarizeReplay);
export const suite: ReviewSuiteIndexEntry = {
  id: 'storybook-suite',
  title: 'Checkout regression review',
  createdAt: samples[0]!.meta.capturedAt,
  runs: 6,
  running: 1,
  failed: 1,
  partial: 1,
  missingRecordings: 0,
  duration: 48000,
  subject: {
    provider: 'github',
    label: 'Checkout fix #42',
    url: 'https://github.com/example/shop/pull/42',
  },
  runDetails: summaries.map((summary, i) => ({
    id: `run-${i}`,
    sequence: i + 1,
    label: summary.title,
    status: i === 0 ? 'failed' : i === 1 ? 'running' : 'passed',
    startedAt: summary.capturedAt,
    replayId: summary.id,
    replay: summary,
  })),
};
export function feedEntries(count = 6): FeedEntry[] {
  return Array.from({ length: count }, (_, i) => {
    const summary = {
      ...summaries[i % summaries.length]!,
      id: `story-${i}`,
      capturedAt: new Date(Date.parse(samples[0]!.meta.capturedAt) - i * 3600000).toISOString(),
    };
    return { kind: 'session', id: summary.id, summary };
  });
}
export const suiteEntry: FeedEntry = {
  kind: 'suite',
  id: suite.id,
  suite,
  status: 'Failed',
  runs: suite.runDetails,
  hiddenRuns: 0,
  hosts: ['checkout.northstar.demo.test'],
};
